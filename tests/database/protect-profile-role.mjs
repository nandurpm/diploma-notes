import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
CREATE FUNCTION public.is_blog_owner() RETURNS boolean LANGUAGE sql SECURITY DEFINER AS $$ SELECT auth.uid() = '00000000-0000-0000-0000-000000000001'::uuid $$;
CREATE TABLE public.profiles (id int primary key, role text);
GRANT USAGE ON SCHEMA public,auth TO anon,authenticated,service_role;
GRANT ALL ON profiles TO anon,authenticated,service_role;
INSERT INTO profiles VALUES (1,'student');`);
await db.exec(fs.readFileSync(process.argv[2],'utf8'));
await db.exec(`CREATE TRIGGER profiles_protect_role BEFORE INSERT OR UPDATE OF role ON profiles FOR EACH ROW EXECUTE FUNCTION protect_profile_role();`);
await db.exec(`SET ROLE authenticated; SET test.uid='00000000-0000-0000-0000-000000000002'; UPDATE profiles SET role='admin' WHERE id=1;`);
assert.equal((await db.query('SELECT role FROM profiles WHERE id=1')).rows[0].role,'student');
await db.exec(`INSERT INTO profiles VALUES (2,'admin');`);
assert.equal((await db.query('SELECT role FROM profiles WHERE id=2')).rows[0].role,'student');
await db.exec(`SET test.uid='00000000-0000-0000-0000-000000000001'; UPDATE profiles SET role='owner' WHERE id=1;`);
assert.equal((await db.query('SELECT role FROM profiles WHERE id=1')).rows[0].role,'owner');
await db.exec(`RESET ROLE; SET test.uid=''; UPDATE profiles SET role='admin' WHERE id=1; SET ROLE service_role; UPDATE profiles SET role='service' WHERE id=1;`);
assert.equal((await db.query('SELECT role FROM profiles WHERE id=1')).rows[0].role,'service');
await db.exec('SET ROLE anon');
await assert.rejects(()=>db.exec(`UPDATE profiles SET role='bad' WHERE id=1`),/Authentication required/);
console.log('PASS: student insert/update, owner, SQL admin, service role and anonymous rejection');
await db.close();
